#pragma once

#include <stdint.h>
#include <stddef.h>
#include <time.h>

#include "arena.h"

/*
 * Positions / Ranges
 *
 * Both types are zero-indexed, matching the LSP specification.
 *
 * Example: the identifier "spec" in the source line (line 2):
 *
 *   task spec "Specification" {
 *   0123456789
 *
 *   LspPos start = { .line = 2, .character = 5 };
 *   LspPos end   = { .line = 2, .character = 9 };
 *   LspRange r   = { .start = start, .end = end };
 */

/** Zero-indexed source position (LSP Position). */
typedef struct {
    uint32_t line;       /**< zero-indexed line number */
    uint32_t character;  /**< zero-indexed UTF-16 code-unit offset within the line */
} LspPos;

/** Half-open source range (LSP Range). */
typedef struct {
    LspPos start;        /**< inclusive start position */
    LspPos end;          /**< exclusive end position */
} LspRange;

/** Bison's end-of-input marker (always 0). */
#define TK_EOF 0

/**
 * Lexer token value passed between bison grammar rules via the %union yylval.
 *
 * TK_* constants are defined in grammar.tab.h (generated by bison) as the
 * yytokentype enum.  Files that compare token kinds must include grammar.tab.h
 * in addition to this header.
 *
 * TK_EOF is bison's EOF marker (always 0) and is not declared in grammar.y.
 *
 * Token is used only for values passed between bison grammar rules via the
 * %union yylval mechanism.  It is not the persistent token store; that is
 * TokenSpan.
 */
typedef struct {
    int    kind;         /**< one of the TK_* / KW_* values from grammar.tab.h */
    LspPos start;        /**< source position of the first character */
    LspPos end;          /**< source position one past the last character */
    char  *text;         /**< borrowed pointer into the parse's token arena
                          *   (interned by g_push_tok_span), or NULL.  Never
                          *   freed via the token; strdup it to keep it. */
} Token;


/* ── tj_node ─────────────────────────────────────────────────────────────── *
 *
 * Generic node type representing a named TaskJuggler declaration:
 * task, account, resource (and shift), report (and related report-type
 * declarations), or project.  The node kind is encoded by the `keyword`
 * field — a raw KW_* / TK_* constant from grammar.tab.h.
 *
 * Memory ownership: every tj_node, its children / dependencies arrays,
 * and the strings they borrow all live in the parse's token arena, which
 * travels into the owning doc_snapshot.  Nothing is freed per node — the
 * whole tree is reclaimed when the snapshot releases the arena.
 * Per-document tj_node trees are immutable after parse — cross-document
 * hoisting lives in a wholly separate per-project tree (project_tree.h),
 * not on these nodes.
 */
typedef struct tj_node tj_node;

/** Direction of a dependency reference. */
typedef enum {
    DEP_KIND_DEPENDS,   /**< `depends <ref>` — this task waits for ref */
    DEP_KIND_PRECEDES   /**< `precedes <ref>` — ref waits for this task */
} DepKind;

/**
 * One captured `depends`/`precedes` reference on a task tj_node.
 *
 * Populated by the grammar action for `dep_ref` at parse time.  These
 * per-document references are left unresolved here; cross-file
 * resolution runs against the assembled per-Project ProjectNode tree
 * and is memoized there (ProjectDep.resolved, see project_tree.h).
 *
 * Memory ownership: the `dependencies` array and `path` both live in the
 * parse's token arena (the array via tj_node_push_dependency, the path via
 * the dep_path rule) and are reclaimed in bulk with it, never freed per
 * dependency.
 */
typedef struct Dependency {
    DepKind   kind;             /**< whether this dep is `depends` or `precedes` */
    int       bang_count;       /**< number of leading `!` characters */
    char     *path;             /**< dotted identifier path; borrowed from the token arena */
    LspRange  source_range;     /**< spans the bang(s) + dotted path in source */
} Dependency;

/**
 * One named declaration in a parsed document: a task, account,
 * resource (or shift), report (or related report-kind), or project.
 * The node kind is identified by the raw `keyword` field, which
 * holds the KW_/TK_ constant the grammar matched.  Generic enough
 * to back document-symbol, completion, definition, references,
 * folding, and dependency resolution — handlers branch on `keyword`
 * when they need to distinguish kinds.
 *
 * Memory: the node itself, `dependencies`, `children`, every reachable
 * child node, and the `id` / `name` lexemes all live in the parse's token
 * arena and are reclaimed with it when the owning doc_snapshot is
 * released; nothing is freed per node.  The cross-tree `parent_node`
 * pointer is borrowed.
 */
struct tj_node {
    /* ── Identity ── */
    int        keyword;        /**< KW_ / TK_ constant from grammar.tab.h; 0 for synthetic per-doc roots */
    char      *id;              /**< TJP identifier; borrowed from the token arena, NULL on synthetic roots */
    char      *name;            /**< display name; borrowed from the token arena, NULL on synthetic roots */

    /* ── Source location ── */
    LspRange   range;           /**< full declaration including body */
    LspRange   selection_range; /**< just the identifier (or keyword) token */

    /* ── Task-only attributes (zero on other kinds) ── */
    time_t     start_date;      /**< explicit `start` date, valid if has_start */
    time_t     end_date;        /**< explicit `end` date, valid if has_end */
    int        has_start;       /**< 1 when start_date is populated */
    int        has_end;         /**< 1 when end_date is populated */

    /* ── Task-only dependencies (zero on other kinds) ──
     *
     * Captured at parse time from `depends` / `precedes` attributes,
     * one entry per dep_ref in source order.  Empty on tasks that
     * declare no dependencies and on every non-task node.  Arena-owned,
     * reclaimed with the parse's token arena. */
    Dependency *dependencies;     /**< owned array; @see num_dependencies */
    int         num_dependencies; /**< number of valid entries in `dependencies` */
    int         dependencies_cap; /**< allocated capacity of `dependencies` */

    /* ── Tree links ──
     *
     * parent_node    — semantic parent in the global tree.  May cross
     *                  document boundaries: when this Document is
     *                  included with a taskprefix, top-level tasks of
     *                  this Document point at the prefix-target node
     *                  in the includer's Document.  In-document
     *                  parents stay within the same Document.
     *                  NULL on the document's synthetic root.
     *
     * children       — locally declared children in source order.
     *                  Arena-owned, reclaimed with the token arena.
     */
    tj_node   *parent_node;  /**< borrowed; see comment above */
    tj_node  **children;     /**< owned array; @see num_children */
    int        num_children; /**< number of valid entries in `children` */
    int        children_cap; /**< allocated capacity of `children` */
};

/**
 * Allocate a zeroed tj_node from the current parse's token arena.  Only
 * valid during a parse (the arena exists between install and harvest of
 * the parser globals); the node is reclaimed with the arena.
 *
 * @return Arena-owned zeroed node; never NULL (aborts on OOM).
 */
tj_node *tj_node_new(void);

/**
 * Append @p child as a locally declared child of @p parent (growing the
 * arena-backed `children` array as needed) and set @p child's
 * `parent_node` to @p parent.
 *
 * @param parent  Owning node.
 * @param child   Child to attach.
 */
void tj_node_append_child(tj_node *parent, tj_node *child);

/**
 * Append a captured dependency reference onto @p task's arena-backed
 * `dependencies` array, growing it as needed.  @p dep.path is arena-owned
 * and simply recorded.
 *
 * @param task  Task tj_node (caller guarantees keyword == KW_TASK).
 * @param dep   Source-position-bearing Dependency whose `path` is heap-owned.
 */
void tj_node_push_dependency(tj_node *task, Dependency dep);

/** Forward declaration; the full struct is defined in diagnostics.h. */
typedef struct Diagnostic Diagnostic;

/**
 * A lexical token with its source location.
 *
 * Used as a flat, ordered sequence for all cursor-position queries: hover,
 * completion, signature help, semantic highlighting, folding ranges, etc.
 *
 * Populated by the lexer for every token that callers may need to inspect:
 *   - All KW_* keyword tokens (including TK_DATE, TK_DURATION, TK_STR, …)
 *   - TK_IDENT, TK_LBRACE, TK_RBRACE, TK_BANG, TK_DOT, TK_COMMA
 *   - TK_LINE_COMMENT, TK_BLOCK_COMMENT
 *
 * `token_kind` holds the raw TK_* / KW_* constant from grammar.tab.h.
 * `text` points into the owning ParseOutput / doc_snapshot's token arena
 * (a NUL-terminated copy of yytext); NULL only for tokens where the text is
 * never needed.  Caller must not modify or free it; it is released in bulk
 * when the arena is freed.
 *
 * The innermost enclosing tj_node for each token (its "owner") is kept in a
 * parallel array (ParseOutput / doc_snapshot `tok_owners`, indexed the same as
 * `tok_spans`) rather than in this struct, so the hot span array stays 32 bytes
 * — two per cache line and far less memory to fill, scan, and owner-annotate.
 */
typedef struct {
    int       token_kind;   /**< raw TK_/KW_ constant from grammar.tab.h */
    LspPos    start;        /**< inclusive start position in the source */
    LspPos    end;          /**< exclusive end position in the source */
    char     *text;         /**< borrowed arena lexeme; may be NULL */
} TokenSpan;

/**
 * Return a retired token-span buffer to the parser's single-entry recycle
 * cache so the next parse can reuse its already-mapped pages instead of
 * mmap-ing (and page-faulting) a fresh multi-MB block.  Called wherever a
 * ParseOutput / doc_snapshot's `tok_spans` would otherwise be free()'d.
 * Thread-safe; surplus buffers (slot already full) are freed.  NULL is a no-op.
 *
 * @param buf  The `tok_spans` buffer being retired (may be NULL).
 */
void tok_spans_release(TokenSpan *buf);

/* ── Include prefixes ────────────────────────────────────────────────────── *
 *
 * TaskJuggler's include directive can prefix the includee's declarations
 * into one dotted namespace per kind (`taskprefix`, `accountprefix`,
 * `resourceprefix` — shared with shifts — and `reportprefix`).  The same
 * four-slot set travels from the IncludeRef captured at parse time onto
 * the includee's Document and into every workspace snapshot, so it gets
 * one type instead of four parallel fields on each struct.
 */

/**
 * The per-kind id namespace a prefix applies to.  The enumerators MUST
 * stay in the same order as project_tree.h's NodeKind (task, account,
 * resource, report), so a NodeKind can index a prefix_set directly;
 * workspace.c static-asserts the correspondence.
 */
typedef enum {
    PREFIX_TASK,        /**< `taskprefix` — task namespace */
    PREFIX_ACCOUNT,     /**< `accountprefix` — account namespace */
    PREFIX_RESOURCE,    /**< `resourceprefix` — resource and shift namespace */
    PREFIX_REPORT,      /**< `reportprefix` — report-family namespace */
    PREFIX_KIND_COUNT   /**< number of prefix kinds */
} prefix_kind;

/** One owned dotted-path prefix per kind; a NULL slot means "no prefix". */
typedef struct {
    char *by_kind[PREFIX_KIND_COUNT]; /**< owned strings, or NULL */
} prefix_set;

/**
 * Free every owned string in @p ps and NULL the slots.  Safe on a
 * zero-initialized set.
 *
 * @param ps  Set to clear; must be non-NULL.
 */
void prefix_set_clear(prefix_set *ps);

/**
 * Replace @p dst's contents with a deep copy of @p src (releasing whatever
 * @p dst held).  @p src may be NULL, which just clears @p dst.
 *
 * @param dst  Destination set; must be non-NULL.
 * @param src  Source set to copy, or NULL.
 */
void prefix_set_copy(prefix_set *dst, const prefix_set *src);

/**
 * Read one slot of a possibly-NULL prefix_set.
 *
 * @param ps  Set to read, or NULL.
 * @param k   Which kind's prefix to fetch.
 * @return    Borrowed prefix string, or NULL when absent.
 */
static inline const char *prefix_get(const prefix_set *ps, prefix_kind k) {
    return ps ? ps->by_kind[k] : NULL;
}

/**
 * One entry per `include` directive seen in the source.  `filename` is the
 * unquoted target as it appeared in the include statement; `prefixes`
 * carries the per-kind prefix attributes from the include body (e.g.
 * `include "bar.tji" { taskprefix t1.t2 }`).  All strings are
 * heap-allocated and owned by the ParseOutput that holds the IncludeRef.
 */
typedef struct {
    char       *filename; /**< owned unquoted target as it appeared in the include statement */
    prefix_set  prefixes; /**< owned per-kind prefixes from the include body */
} IncludeRef;

/**
 * The complete output of a single parse() call for one document.
 *
 * One ParseOutput per parse — its lifetime is tied to the owning Document
 * (the server creates a fresh one on every didOpen/didChange and frees the
 * previous one).  All arrays and tj_node subtrees referenced from here are
 * owned by this struct and freed by parse_output_free().
 *
 * The synthetic `root` is always non-NULL.  Its `keyword` is 0; its
 * `children` array holds every top-level declaration of the document —
 * tasks, accounts, resources/shifts, the report family, and the project
 * block — in source order.  A `project ... { ... }` block's own body
 * declarations are hoisted to siblings under `root` (the project node
 * keeps no children); `assign_token_owners()` restores that nesting for
 * token ownership only.  The tree is immutable after parse —
 * cross-Document hoisting happens in a separately allocated global tree
 * built by server.c.
 */
typedef struct {
    tj_node   *root;         /**< synthetic root; children are all top-level declarations in source order */

    TokenSpan *tok_spans;       /**< owned flat array of every captured token */
    int        num_tok_spans;   /**< number of valid entries in `tok_spans` */
    int        num_sem_entries; /**< upper bound on semantic-token entries (one per source line covered) */
    str_arena *tok_arena;       /**< owned backing store for every `tok_spans[i].text` */
    tj_node  **tok_owners;      /**< owned array[num_tok_spans]; innermost enclosing node per token (parallel to tok_spans), or NULL */

    IncludeRef *includes;       /**< owned array; one entry per `include` directive */
    int         num_includes;   /**< number of valid entries in `includes` */
    int         includes_cap;   /**< allocated capacity of `includes` */
} ParseOutput;

/* ── Public API ──────────────────────────────────────────────────────────── */

/**
 * Parse @p src into a ParseOutput.  Single entry point for the lexer +
 * grammar pipeline.
 *
 * @param src  NUL-terminated TaskJuggler source text.
 * @return Heap-allocated ParseOutput.  Free with parse_output_free().
 */
ParseOutput *parse(const char *src);

/**
 * Release every dynamic allocation owned by @p po and free @p po itself.
 * Safe to call with @p po == NULL.
 *
 * @param po  ParseOutput to free.
 */
void parse_output_free(ParseOutput *po);

/**
 * Append an `include` directive entry to @p po->includes.  The prefix set
 * is deep-copied, so the caller retains ownership of its input.
 *
 * @param po           ParseOutput being populated.
 * @param quoted_text  Raw `include` argument as it appears in source;
 *                     the surrounding quotes are stripped before storing.
 * @param prefixes     Per-kind prefix attributes from the include body;
 *                     may be NULL (no prefixes).
 */
void push_include(ParseOutput *po, const char *quoted_text,
                  const prefix_set *prefixes);

/**
 * Parse a `YYYY-MM-DD` date prefix from a TaskJuggler `TK_DATE` token's
 * text into a UTC `time_t`.  Trailing time and timezone components
 * (e.g. `-09:00`, `+0100`) are accepted but ignored.
 *
 * @param text  NUL-terminated token text.  May be NULL.
 * @param out   Receives the parsed time_t on success.
 * @return 1 on success, 0 if @p text does not start with a valid date.
 */
int parse_tjp_date(const char *text, time_t *out);

/**
 * Compare two positions in source order.
 *
 * @param a  Left-hand position.
 * @param b  Right-hand position.
 * @return -1 if @p a precedes @p b, 1 if @p a follows @p b, 0 if equal.
 */
static inline int pos_cmp(LspPos a, LspPos b) {
    if (a.line != b.line) return (a.line < b.line) ? -1 : 1;
    if (a.character != b.character) return (a.character < b.character) ? -1 : 1;
    return 0;
}
